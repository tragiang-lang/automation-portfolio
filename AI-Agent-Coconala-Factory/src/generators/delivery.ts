export function spreadsheetSetupMd(input: DeliveryInputs): string {
  const { brief, schema, configSeed, trace } = input;
  const sheets = schema.sheets
    .map((sheet) => {
      const rows = sheet.columns.map((c) => `| \`${c.name}\` | ${c.required ? "必須" : ""} | ${c.description}${c.pii ? "（個人情報）" : ""} |`);
      return `### \`${sheet.name}\`\n\n| 列 | | 内容 |\n|---|---|---|\n${rows.join("\n")}`;
    })
    .join("\n\n");
  const config = schema.configKeys.map((k) => {
    const value = configSeed[k.key] ?? k.default;
    return `| \`${k.key}\` | ${k.required ? "必須" : ""} | ${k.description} | ${value !== undefined ? `\`${value}\`` : "（未入力）"} |`;
  });
  return `# スプレッドシートの構成 — ${brief.project.clientName}

シートは Apps Script の **setupSpreadsheet** で自動作成されます（[SETUP.md](SETUP.md)「4」）。手で作る必要はありません。
**1行目（見出し）の名前は変更しないでください。** 列の順番の入れ替えや、右側への列の追加は問題ありません。

## シートと列

${sheets}

## \`CONFIG\` シートの設定項目

初期値はご要望の内容から入力済みです。変更は \`value\` 列を書き換えるだけで、すぐに反映されます。

| key | | 内容 | 初期値 |
|---|---|---|---|
${config.join("\n")}

## 個人情報の扱い

「（個人情報）」と書かれた列には、お客様の LINE ID・お名前・連絡先・お問い合わせ内容が入ります。
スプレッドシートの共有は必要な方だけにし、不要になったデータは定期的に削除してください。
${footer(trace)}`;
}

