const footer = (trace: TraceContext) =>
  `\n---\n\n<sub>Generated by AI-Agent-Coconala-Factory ${FACTORY_VERSION} for ${trace.project} (${trace.industry}; ${trace.workflows.join(", ")}).</sub>\n`;

const hasWorkflow = (plan: WorkflowPlan, prefix: string) => plan.selected.some((w) => w.id.startsWith(prefix));

/** What the customer sees after tapping a button, derived from the button's LINE action and route. */
function expectedResult(area: LineRichMenuConfig["areas"][number], routes: LineRoute[]): string {
  const action = area.action;
  if (action.type === "uri") return "ブラウザで Web ページが開く";
  if (action.type === "datetimepicker") return "日時を選ぶ画面が出て、選ぶと「予約リクエストを受け付けました」と返信が届く";
  const params = Object.fromEntries((action.data ?? "").split("&").map((pair) => pair.split("=")));
  const route = routes.find((r) => r.workflowId === params.wf && r.entry === (params.e ?? "default"));
  if (route?.mode === "awaitText") return "案内メッセージが届き、続けて内容を送ると「受け付けました」と受付番号が届く";
  return "店舗の情報がメッセージで届く";
}

