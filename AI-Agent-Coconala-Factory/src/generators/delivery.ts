export function rollbackMd(input: DeliveryInputs): string {
  const { brief, trace } = input;
  const slugPath = `projects/${trace.project}`;
  return `# 元に戻す方法 — ${brief.project.clientName}

困ったときは、まず「どこを戻すか」を決めます。どの手順も、お客様のデータ（スプレッドシート）は消しません。

## 1. リッチメニューを前のものに戻す

作業者向け（ファクトリーから）:

\`\`\`bash
npm run factory -- line-rollback --project ${slugPath} --env production          # 確認だけ
LINE_CHANNEL_ACCESS_TOKEN=… npm run factory -- line-rollback --project ${slugPath} --env production --live
\`\`\`

- 直前に登録していたメニューを「全員に表示」に戻します。メニューは削除しません。
- 登録前にメニューがなかった場合は戻す先がないため、LINE Official Account Manager でメニューを表示する設定にするか、作業者が \`line/deployment-history.json\` を確認して対応します。
- 不要になったメニューの削除は、表示中でないことを確認してから \`line-delete --rich-menu-id <ID> --live\` で行います（表示中のメニューは削除できないようになっています）。

## 2. LINE との接続（Webhook）を止める・戻す

- **すぐに止めたいとき:** LINE Developers →「Messaging API設定」→「Webhookの利用」をオフにします。自動受付は止まり、通常のチャットと自動応答メッセージだけになります。
- **Webhook URL を間違えたとき:** 署名確認プロキシの \`…workers.dev\` の URL に設定し直し、「検証」で成功を確認します。
- 署名確認プロキシを前の版に戻す（作業者向け）: \`cd line/webhook && npx wrangler rollback\`。

## 3. プログラム（Apps Script）を前の版に戻す

Apps Script エディタ →「デプロイを管理」→ 使用中のデプロイを「編集」→「バージョン」で前の版を選んで「デプロイ」。
URL は変わらないため、署名確認プロキシや LINE の設定は変更不要です。

## 4. 設定を元に戻す

- **\`CONFIG\` シート:** スプレッドシートの「ファイル」→「変更履歴」から、以前の状態に戻せます。
- **スクリプト プロパティ・プロキシの値:** 画面に表示されない値のため、パスワード管理ツールに控えておき、必要なら同じ画面で入れ直します。
- **漏えいしたとき:** LINE Developers でチャネルアクセストークンを再発行し、チャネルシークレットも再発行します。
  新しい値を Apps Script（\`LINE_CHANNEL_ACCESS_TOKEN\`）と署名確認プロキシ（\`npx wrangler secret put LINE_CHANNEL_SECRET\`）に設定し、
  \`WEBHOOK_KEY\` も新しい値にして Apps Script とプロキシ（\`GAS_WEBHOOK_KEY\`）の両方を更新します。

## 記録

登録・切り戻しの履歴は \`line/deployment-history.json\` にあります（トークンなどの秘密の値は記録されません）。
${footer(trace)}`;
}

